it('refuses files alongside a url source, and a file source with no files', function (): void {
    $f = sourceUploadFixture();

    SpaSession::establish(currentTest(), $f['ownerA']);

    currentTest()->post(
        "/api/v1/organizations/{$f['orgA']->id}/sources",
        [
            'type' => 'url',
            'name' => 'Docs site',
            'origin_url' => 'https://example.com/docs',
            'files' => [sourceUploadFile('Handbook.pdf', sourceUploadPdfBytes())],
        ],
        spaHeaders(),
    )->assertStatus(422)->assertJsonStructure(['errors' => ['files']]);

    currentTest()->post(
        "/api/v1/organizations/{$f['orgA']->id}/sources",
        ['type' => 'file', 'name' => 'Empty'],
        spaHeaders(),
    )->assertStatus(422)->assertJsonStructure(['errors' => ['files']]);

    expect(KnowledgeSource::query()->withoutGlobalScopes()->count())->toBe(0);
});

it('refuses a batch larger than the published cap, without opening a single file', function (): void {
    $f = sourceUploadFixture();

    SpaSession::establish(currentTest(), $f['ownerA']);

    $files = [];

    for ($i = 0; $i <= UploadLimits::maxBatch(); $i++) {
        $files[] = sourceUploadFile("doc{$i}.pdf", sourceUploadPdfBytes()."% {$i}\n");
    }

    currentTest()->post(
        "/api/v1/organizations/{$f['orgA']->id}/sources",
        ['type' => 'file', 'name' => 'Too many', 'files' => $files],
        spaHeaders(),
    )->assertStatus(422)->assertJsonStructure(['errors' => ['files']]);

    // NOTHING WAS SCREENED, so there is no rejection row: the batch cap is the FormRequest's and it
    // runs before the intake. Recording eleven `source.upload.rejected` rows for one over-long batch
    // would bury the rows that mean somebody is probing the gate.
    expect(AuditLog::query()->where('operation', '=', AuditLogger::SOURCE_UPLOAD_REJECTED)->count())->toBe(0);
    expect(Storage::disk('s3')->allFiles())->toBe([]);
});
